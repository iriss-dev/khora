const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const http = require('node:http');
const root = path.resolve(__dirname, '..');
const server = http.createServer((req, res) => {
  let file = path.resolve(root, '.' + decodeURIComponent(new URL(req.url, 'http://localhost').pathname));
  if (!file.startsWith(root + path.sep) && file !== root) return res.writeHead(403).end();
  if (fs.existsSync(file) && fs.statSync(file).isDirectory()) file = path.join(file, 'index.html');
  const types = {'.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.svg': 'image/svg+xml', '.png': 'image/png'};
  fs.readFile(file, (error, data) => {
    if (error) return res.writeHead(404).end();
    res.setHeader('Content-Type', types[path.extname(file)] || 'application/octet-stream');
    res.end(data);
  });
});

(async () => {
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  let browser;
  try {
    browser = await chromium.launch({channel: process.env.KHORA_BROWSER_CHANNEL || 'msedge', headless: true, args: ['--enable-unsafe-swiftshader']});
    const page = await browser.newPage({viewport: {width: 1536, height: 1000}});
    const errors = [], external = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
    await page.route('**/*', route => {
      const url = new URL(route.request().url());
      if (url.hostname !== '127.0.0.1' && !['data:', 'blob:'].includes(url.protocol)) {
        external.push(url.href);
        return route.abort();
      }
      return route.continue();
    });
    const base = `http://127.0.0.1:${server.address().port}`;
    await page.goto(base);
    await page.waitForFunction(() => document.getElementById('preview-pressure')?.textContent.includes('Pa'));
    assert.equal(await page.locator('html').getAttribute('lang'), 'es');
    const languageBounds = await page.locator('#language').boundingBox();
    assert.ok(languageBounds.height >= 44 && languageBounds.width >= 87);
    await page.locator('#language').click();
    assert.match(await page.locator('h1').textContent(), /How an image/);
    assert.equal(await page.locator('#language').getAttribute('aria-pressed'), 'true');
    await page.reload();
    assert.equal(await page.locator('html').getAttribute('lang'), 'en');
    await page.goto(base + '/platform/');
    assert.equal(await page.locator('html').getAttribute('lang'), 'en');
    const darkBackground = await page.locator('body').evaluate(element => getComputedStyle(element).backgroundColor);
    await page.locator('#theme-toggle').click();
    await page.waitForFunction(previous => getComputedStyle(document.body).backgroundColor !== previous, darkBackground);
    assert.equal(await page.locator('html').getAttribute('data-theme'), 'light');
    fs.mkdirSync(path.join(root, 'build'), {recursive: true});
    await page.screenshot({path: path.join(root, 'build/landing-light.png'), animations: 'disabled'});
    await page.reload();
    assert.equal(await page.locator('html').getAttribute('data-theme'), 'light');
    await page.locator('#theme-toggle').click();
    await page.locator('#rig-motion').click();
    assert.equal(await page.locator('#rig-motion').getAttribute('aria-pressed'), 'false');
    const pausedView = await page.locator('#rig-canvas').screenshot();
    await page.waitForTimeout(200);
    assert.deepEqual(await page.locator('#rig-canvas').screenshot(), pausedView);
    await page.locator('#rig-motion').click();
    await page.waitForTimeout(200);
    assert.notDeepEqual(await page.locator('#rig-canvas').screenshot(), pausedView);
    await page.locator('#rig-motion').click();
    await page.locator('[data-rig="optics"]').click();
    assert.equal(await page.locator('[data-rig="optics"]').getAttribute('aria-pressed'), 'true');
    assert.match(await page.locator('#rig-description').textContent(), /array is hidden/);
    await page.waitForTimeout(700);
    const opticalView = await page.locator('#rig-canvas').screenshot();
    fs.writeFileSync(path.join(root, 'build/rig-optics.png'), opticalView);
    await page.locator('[data-rig="haptics"]').click();
    assert.match(await page.locator('#rig-description').textContent(), /plate are hidden/);
    await page.waitForTimeout(700);
    const acousticView = await page.locator('#rig-canvas').screenshot();
    fs.writeFileSync(path.join(root, 'build/rig-ultrasound.png'), acousticView);
    assert.notDeepEqual(opticalView, acousticView);
    await page.locator('[data-rig="all"]').click();
    await page.locator('#rig-reset').click();
    await page.locator('.process-step[data-step="2"]').click();
    assert.equal(await page.locator('#process-diagram').getAttribute('data-step'), '2');
    assert.match(await page.locator('#diagram-caption').textContent(), /no physical screen/);
    await page.locator('.process-step[data-step="3"]').click();
    assert.match(await page.locator('#diagram-caption').textContent(), /requires measurements/);
    await page.locator('#guide-play').click();
    assert.equal(await page.locator('#guide-play').getAttribute('aria-pressed'), 'true');
    await page.waitForFunction(() => document.getElementById('process-diagram').dataset.step === '1', {timeout: 7000});
    await page.locator('#guide-play').click();
    const before = await page.locator('#preview-pressure').textContent();
    await page.locator('#preview-focus').fill('40');
    await page.waitForFunction(() => document.getElementById('preview-value').textContent === '40 mm');
    assert.notEqual(await page.locator('#preview-pressure').textContent(), before);
    await page.locator('#preview-height').fill('180');
    await page.waitForFunction(() => document.getElementById('preview-height-value').textContent === '180 mm');
    await page.locator('#preview-open').click();
    await page.waitForFunction(() => document.getElementById('field-x-value')?.textContent === '40 mm');
    assert.equal(await page.locator('#field-z').inputValue(), '180');
    await page.goto(base + '/platform/');
    await page.waitForFunction(() => document.getElementById('preview-pressure').textContent.includes('Pa'));
    await page.locator('#preview-sweep').click();
    await page.waitForFunction(() => Math.abs(Number(document.getElementById('preview-focus').value)) > 8);
    await page.locator('#preview-sweep').click();
    const stoppedPosition = await page.locator('#preview-focus').inputValue();
    await page.waitForTimeout(300);
    assert.equal(await page.locator('#preview-focus').inputValue(), stoppedPosition);
    await page.locator('#preview-reset').click();
    await page.waitForFunction(() => document.getElementById('preview-value').textContent === '0 mm');
    const plot = await page.locator('#preview-canvas').boundingBox();
    await page.mouse.click(plot.x + plot.width * .6, plot.y + plot.height / 3);
    await page.waitForFunction(() => document.getElementById('preview-value').textContent === '32 mm');
    assert.equal(await page.locator('#preview-height').inputValue(), '180');
    fs.mkdirSync(path.join(root, 'build'), {recursive: true});
    const layouts = [];
    for (const width of [1536, 768, 390, 360]) {
      await page.setViewportSize({width, height: width > 768 ? 1000 : 844});
      const measured = await page.evaluate(() => ({width: innerWidth, content: document.documentElement.scrollWidth}));
      assert.ok(measured.content <= measured.width, JSON.stringify(measured));
      layouts.push(measured);
      await page.evaluate(() => document.querySelectorAll('.reveal-ready').forEach(element => element.classList.add('is-visible')));
      await page.screenshot({path: path.join(root, `build/landing-${width}.png`), fullPage: true, animations: 'disabled'});
    }
    await page.locator('#language-es').click();
    await page.setViewportSize({width: 360, height: 844});
    assert.equal(await page.locator('html').getAttribute('lang'), 'es');
    assert.match(await page.locator('#rig-description').textContent(), /La placa/);
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({path: path.join(root, 'build/landing-es-mobile.png'), fullPage: true, animations: 'disabled'});
    const localLinks = await page.locator('a[href]').evaluateAll(elements => [...new Set(elements.map(a => a.href).filter(href => href.startsWith(location.origin)))]);
    for (const href of localLinks) assert.ok((await page.request.get(href)).ok(), href);
    const fallback = await browser.newPage();
    await fallback.addInitScript(() => {
      const getContext = HTMLCanvasElement.prototype.getContext;
      HTMLCanvasElement.prototype.getContext = function (kind, ...args) {
        return kind.includes('webgl') ? null : getContext.call(this, kind, ...args);
      };
    });
    await fallback.goto(base + '/platform/');
    assert.equal(await fallback.locator('#rig-fallback').isVisible(), true);
    assert.equal(await fallback.locator('#preview-error').isVisible(), true);
    assert.match(await fallback.locator('#preview-pressure').textContent(), /Pa/);
    assert.equal(await fallback.locator('#rig-fallback img').evaluate(img => img.complete && img.naturalWidth > 0), true);
    const reduced = await browser.newPage({reducedMotion: 'reduce'});
    await reduced.goto(base + '/platform/');
    assert.equal(await reduced.locator('#rig-motion').getAttribute('aria-pressed'), 'false');
    assert.equal(await reduced.locator('.light-travel').evaluate(element => getComputedStyle(element).animationName), 'none');
    assert.deepEqual(errors, []);
    assert.deepEqual(external, []);
    console.log(JSON.stringify({result: 'passed', layouts, checkedLinks: localLinks.length, browserErrors: errors.length, externalRequests: external.length, webglFallback: true}, null, 2));
  } finally {
    await browser?.close();
    await new Promise(resolve => server.close(resolve));
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
